    @Test("stripMarkdownSyntax(from:) returns what it returned before the speed-up, with and without list markers")
    func stripMarkdownSyntaxIsUnchanged() {
        for (index, pinned) in Self.cases.enumerated() {
            #expect(MarkdownUtils.stripMarkdownSyntax(from: pinned.input) == pinned.stripped,
                    "case \(index): \(pinned.input.debugDescription)")
            #expect(MarkdownUtils.stripMarkdownSyntax(from: pinned.input, stripListMarkers: false) == pinned.strippedKeepingListMarkers,
                    "case \(index) without list markers: \(pinned.input.debugDescription)")
        }
    }

    @Test("stripAnnotations(from:) returns what it returned before the speed-up")
    func stripAnnotationsIsUnchanged() {
        for (index, pinned) in Self.cases.enumerated() {
            #expect(MarkdownUtils.stripAnnotations(from: pinned.input) == pinned.annotationsStripped,
                    "case \(index): \(pinned.input.debugDescription)")
        }
    }

    @Test("stripForWordCount(from:) and wordCount(for:) return what they returned before the speed-up")
    func wordCountPipelineIsUnchanged() {
        for (index, pinned) in Self.cases.enumerated() {
            #expect(MarkdownUtils.stripForWordCount(from: pinned.input) == pinned.forWordCount,
                    "case \(index): \(pinned.input.debugDescription)")
            #expect(MarkdownUtils.wordCount(for: pinned.input) == pinned.words,
                    "case \(index) word count: \(pinned.input.debugDescription)")
        }
    }

    @Test("Removing bold markers can produce an image; the image step still sees it")
    func boldMarkersAroundAnImageOpeningStillProduceAnImage() {
        // `!**[a**](b)` -> (bold) `![a](b)` -> (image) ``: the text the image step runs on is not the text the call started with.
        #expect(MarkdownUtils.stripMarkdownSyntax(from: "!**[a**](b)") == "")
        // The same shape with a leading word keeps the word.
        #expect(MarkdownUtils.stripMarkdownSyntax(from: "see !**[a**](b)") == "see ")
    }
